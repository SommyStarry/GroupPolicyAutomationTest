}

}

#------------------------------------------------------------SERVICES---------------------------------------#
#Спільна функція застосування типів запуску "Сервісів"
# $Services       - масив @{ Name = "..."; StartType = "Auto|Demand|Disabled" }
# $PromptServices - необов'язково: для зазначених служб користувачу пропонується вибір (1 - значення Enabled, 2 - DISABLED, 3 - пропустити)
function Set-ServicesStartType {
    param (
        [Parameter(Mandatory)] [array]$Services,
        [hashtable]$PromptServices = @{}
    )

    foreach ($service in $Services) {
        try {
            # Запит конфігурації служби
            $serviceInfo = sc.exe qc $service.Name 2>&1

            # Перевірка на наявність служби (код 1060 = служби не існує, не залежить від мови ОС)
            if ($LASTEXITCODE -eq 1060 -or $serviceInfo -match "The specified service does not exist") {
                Write-Host "Служби --> $($service.Name) <-- не існує в даній збірці Windows" -ForegroundColor Magenta
                Write-Host "---------------------------------------------------------------------------" -ForegroundColor DarkYellow
                continue
            }

            # Витягування поточного типу запуску з конфігурації служби
            $currentServiceStartType = ($serviceInfo | Select-String "START_TYPE" | ForEach-Object { ($_ -split ":")[1].Trim() }) -replace '^\d+\s*', ''
            $currentServiceStartType = $currentServiceStartType.Split('_')[0]
            $serviceTrueName = Get-WmiObject -Class Win32_Service -Filter "Name='$($service.Name)'"
            $displayName = $serviceTrueName.DisplayName

            # Перетворення значень на однаковий формат для порівняння
            $currentServiceStartType = $currentServiceStartType.ToUpper()
            $desiredStartType = $service.StartType.ToUpper()

            # Службі потрібен вибір користувача
            if ($PromptServices.ContainsKey($service.Name)) {
                $prompt = $PromptServices[$service.Name]

                Write-Host ""
                Write-Host "Служба: $displayName ($($service.Name))" -ForegroundColor Cyan
                Write-Host "Поточний тип запуску: $currentServiceStartType"
                Write-Host "Виберіть новий тип запуску:"
                Write-Host "Звертаю увагу, що згідно базового профілю дана служба має бути - Вимкнена !!!" -ForegroundColor Red
                Write-Host $prompt.Hint -ForegroundColor Cyan
                Write-Host ""
                Write-Host $prompt.EnabledLabel
                Write-Host "[2] DISABLED (Вимкнути)"
                Write-Host "[3] Пропустити (Залишити поточний стан)"
                do {
                    $choice = Read-Host "Ваш вибір (1/2/3)"
                } while ($choice -notin '1','2','3')

                if ($choice -eq '3') {
                    Write-Host "Залишено без змін: $displayName" -ForegroundColor Yellow
                    Write-Host "---------------------------------------------------------------------------" -ForegroundColor DarkYellow
                    continue
                }

                $desiredStartType = if ($choice -eq '1') { $prompt.Enabled } else { "DISABLED" }
            }

            # Перевірка, чи відрізняється поточний тип запуску від бажаного
            if ($currentServiceStartType -ne $desiredStartType) {
                Write-Host "Змінюється тип запуску служби --> $displayName <-- з $currentServiceStartType на $desiredStartType" -ForegroundColor Cyan
                sc.exe config $service.Name start= $desiredStartType.ToLower() | Out-Null

                # Підтвердження зміни
                $newServiceStatus = (sc.exe qc $service.Name | Select-String "START_TYPE" | ForEach-Object { ($_ -split ":")[1].Trim() }) -replace '^\d+\s*', ''
                $newServiceStatus = $newServiceStatus.Split('_')[0].ToUpper()

                Write-Host "Служба --> $($service.Name) <-- . Новий статус служби --> $newServiceStatus <--" -ForegroundColor Green
                Write-Host "---------------------------------------------------------------------------" -ForegroundColor DarkYellow
            } else {
                Write-Host "Служба --> $displayName <-- Вже має правильний тип запуску: $currentServiceStartType" -ForegroundColor Yellow
                Write-Host "---------------------------------------------------------------------------" -ForegroundColor DarkYellow
            }
        } catch {
            Write-Host "Не вдалося змінити параметр служби $($service.Name). Помилка: $_" -ForegroundColor Red
        }
    }
}

