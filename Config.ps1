if (Test-Path $tcpipPath) {
    Set-ItemProperty -Path $tcpipPath -Name "EnableICMPRedirect" -Value 0 -Force
    Write-Host "ICMP Redirect вимкнено." -ForegroundColor Green
} else {
    Write-Host "Розділ реєстру ICMP Redirect не знайдено." -ForegroundColor Red
}

# Вимкнути автозапуск для всіх носіїв (NoDriveTypeAutoRun)
$explorerPath = "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\Explorer"
