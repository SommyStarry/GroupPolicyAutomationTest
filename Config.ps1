function restoreToDefaultPolicies {

try {
    $GuestName = (Get-LocalUser | Where-Object { $_.SID -like "*-501" }).Name
    if ($GuestName -and $GuestName -ne "Guest") {
        Rename-LocalUser -Name $GuestName -NewName "Guest"
    }
    
    Write-Host "Скидання локальних групових політик (GPO) до стандартних значень..."

    # Видалення папки Local Group Policy
    Remove-Item -Path "$env:SystemRoot\System32\GroupPolicy" -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -Path "$env:SystemRoot\System32\GroupPolicyUsers" -Recurse -Force -ErrorAction SilentlyContinue

    # Відновлення до стандартних гілки - "Локальні політики ПК -> Налаштування Windows -> Security Policies"
    secedit /configure /db "$env:TEMP\secedit.sdb" /cfg ".\Configs\LGPO-Default\LGPO-Default-Security-Settings.inf" /overwrite /quiet

    # Оновлення політик, щоб зміни набрали чинності
    gpupdate /force

    Write-Host "Локальні GPO скинуто. Далі будуть налаштовані 'Сервіси' "

    pause

    defaultServices
    
}
catch {
    Write-Host "Помилка під час скидання локальних політик: $($_.Exception.Message)"
}

$choiceDefaultPolicies= (Read-Host "Перезавантажити систему ? Так(Y), Повернутись до головного меню (N), Вийти (X)").ToUpper()
    switch ($choiceDefaultPolicies) {
        "Y" { RebootSystem }
        "N" { Start-Menu }
        "X" { End }
        default { Write-Host "Invalid choice, try again."; End}
        }

}

function Remove-Win11TerminalAndPowerShell {
    function RemoveTerm-Menu {
        Write-Host "Видалення Windows Terminal + PowerShell з контекстного меню (Win+X)" -ForegroundColor Cyan
        Write-Host "Оберіть варіант:" -ForegroundColor Cyan
        Write-Host "1. Залишити Windows Terminal + PowerShell лише поточному користувачу, $($env:USERNAME)"
        Write-Host "2. Видалити для всіх (включно з поточним та майбутніми)"
        Write-Host "3. Пропустити видалення"
    }

    function Remove-WinXShortcuts {
        param (
            [string]$ExcludeUser = ""
        )

        Write-Host "Видалення ярликів PowerShell та Windows Terminal з меню Win+X..." -ForegroundColor Yellow
        $patterns = @("*PowerShell*.lnk", "*Windows Terminal*.lnk")

        $usersFolders = @()
        foreach ($user in Get-ChildItem 'C:\Users' -Directory) {
            $winXPath = "$($user.FullName)\AppData\Local\Microsoft\Windows\WinX"
            if ($user.Name -ne "Default" -and $user.Name -ne "Public" -and $user.Name -ne $ExcludeUser -and (Test-Path $winXPath)) {
                $usersFolders += $winXPath
            }
        }

        foreach ($path in $usersFolders) {
            foreach ($pattern in $patterns) {
                Get-ChildItem -Path $path -Recurse -Include $pattern -ErrorAction SilentlyContinue |
                    Remove-Item -Force -ErrorAction SilentlyContinue
            }
        }

        # Також з профілю Default
        $defaultPath = "C:\Users\Default\AppData\Local\Microsoft\Windows\WinX"
        if (Test-Path $defaultPath) {
            foreach ($pattern in $patterns) {
                Get-ChildItem -Path $defaultPath -Recurse -Include $pattern -ErrorAction SilentlyContinue |
                    Remove-Item -Force -ErrorAction SilentlyContinue
            }
        }

        Write-Host "Ярлики PowerShell/Terminal прибрано з Win+X" -ForegroundColor Green
    }

    RemoveTerm-Menu
    $choice = Read-Host "Введіть номер опції (1-3)"
    $currentUser = $env:USERNAME

    switch ($choice) {
      '1' {
            $currentUser = $env:USERNAME
            Write-Host "Видалення Windows Terminal і PowerShell для всіх, крім поточного користувача: $currentUser" -ForegroundColor Yellow

            # Видалення Provisioned Package (для майбутніх користувачів)
            Get-AppxProvisionedPackage -Online | Where-Object DisplayName -EQ "Microsoft.WindowsTerminal" |
                Remove-AppxProvisionedPackage -Online -ErrorAction SilentlyContinue

            # Інші користувачі (крім поточного)
            $users = @()
            foreach ($user in Get-ChildItem "C:\Users" -Directory) {
                $packagePath = "$($user.FullName)\AppData\Local\Packages"
                if ($user.Name -ne "Default" -and $user.Name -ne "Public" -and $user.Name -ne $currentUser -and (Test-Path $packagePath)) {
                    $users += $user
                }
            }

            foreach ($user in $users) {
                $terminalPath = "$($user.FullName)\AppData\Local\Packages\Microsoft.WindowsTerminal_8wekyb3d8bbwe"
                if (Test-Path $terminalPath) {
                    try {
                        Remove-Item -Path $terminalPath -Recurse -Force -ErrorAction SilentlyContinue
                        Write-Host "Видалено Terminal для: $($user.Name)" -ForegroundColor Green
                    } catch {
                        Write-Warning "Не вдалося видалити для $($user.Name): $_"
                    }
                }
            }

            # Видалення ярликів Win+X (крім поточного)
            Remove-WinXShortcuts -ExcludeUser $currentUser
         }

        '2' {
            Write-Host "Повне видалення Windows Terminal і PowerShell для всіх користувачів та майбутніх" -ForegroundColor Yellow

            # Поточний користувач
            Get-AppxPackage -Name "Microsoft.WindowsTerminal" | Remove-AppxPackage -ErrorAction SilentlyContinue

            # Provisioned Terminal
            Get-AppxProvisionedPackage -Online | Where-Object DisplayName -EQ "Microsoft.WindowsTerminal" |
                Remove-AppxProvisionedPackage -Online -ErrorAction SilentlyContinue

            # Інші користувачі
            $users = @()
            foreach ($user in Get-ChildItem "C:\Users" -Directory) {
                $packagePath = "$($user.FullName)\AppData\Local\Packages"
                if ($user.Name -ne "Default" -and $user.Name -ne "Public" -and (Test-Path $packagePath)) {
                    $users += $user
                }
            }

            foreach ($user in $users) {
                $terminalPath = "$($user.FullName)\AppData\Local\Packages\Microsoft.WindowsTerminal_8wekyb3d8bbwe"
                if (Test-Path $terminalPath) {
                    try {
                        Remove-Item -Path $terminalPath -Recurse -Force -ErrorAction SilentlyContinue
                        Write-Host "Видалено Terminal для: $($user.Name)" -ForegroundColor Green
                    } catch {
                        Write-Warning "Не вдалося видалити для $($user.Name): $_"
                    }
                }
            }

            Remove-WinXShortcuts
        }

