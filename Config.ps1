#Додаткові налаштування реєстру
function RegConfig {

#Встановлення значення параметру CrashOnAuditFail = 0
$pathCrashOnFail = "HKLM:\SYSTEM\CurrentControlSet\Control\Lsa"
$nameCrashOnFail = "CrashOnAuditFail"

# Отримуємо поточне значення
$currentValueCrashOnFail = Get-ItemProperty -Path $pathCrashOnFail -Name $nameCrashOnFail -ErrorAction SilentlyContinue | Select-Object -ExpandProperty $nameCrashOnFail

# Якщо значення відсутнє або не дорівнює 0, змінюємо його
if ($currentValueCrashOnFail -ne 0) {
    New-ItemProperty -Path $pathCrashOnFail -Name $nameCrashOnFail -Value 0 -PropertyType DWord -Force | Out-Null
    Write-Host "Значення $nameCrashOnFail змінено на 0." -ForegroundColor Green
} else {
    Write-Host "Значення $nameCrashOnFail вже дорівнює 0. Зміни не потрібні." -ForegroundColor Yellow
}


# Вимкнення автоматичного входу в систему адміністратора
$winlogonPath = "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon"
if (Test-Path $winlogonPath) {
    Set-ItemProperty -Path $winlogonPath -Name "AutoAdminLogon" -Value 0 -Force
    Write-Host "Автовхід адміністратора вимкнено." -ForegroundColor Green
} else {
    Write-Host "Розділ реєстру Winlogon не знайдено." -ForegroundColor Red
}

# Рівень захисту IP-маршрутизації джерела
$tcpipPath = "HKLM:\System\CurrentControlSet\Services\Tcpip\Parameters"
if (Test-Path $tcpipPath) {
    Set-ItemProperty -Path $tcpipPath -Name "DisableIPSourceRouting" -Value 2 -Force
    Write-Host "IP Source Routing вимкнено." -ForegroundColor Green
} else {
    Write-Host "Розділ реєстру TCP/IP не знайдено." -ForegroundColor Red
}

