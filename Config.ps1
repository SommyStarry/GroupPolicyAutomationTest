function CheckWinVersion {
    # Отримати інформацію про ОС
    $os = Get-CimInstance Win32_OperatingSystem
    $build = [int]$os.BuildNumber
    $caption = $os.Caption
    $version = $os.Version

    # Логіка визначення версії
    if ($build -ge 22000) {
        return "Windows 11"
    }
    elseif ($build -lt 22000 -and $build -ge 10240) {
        return "Windows 10"
    }
    else {
        return "Unknown"
    }
}

