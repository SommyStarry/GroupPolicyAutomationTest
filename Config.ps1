    Set-ItemProperty -Path $tcpipPath -Name "DeadGWDetectDefault" -Value 0 -Force
    Write-Host "Виявлення мертвих шлюзів вимкнено." -ForegroundColor Green
} else {
    Write-Host "Розділ реєстру ""Виявлення мертвих шлюзів вимкнено"" не знайдено." -ForegroundColor Red
}


