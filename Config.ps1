function ChangeDefaultUserPath{

# Новий шлях для профілів
$newProfilePath = "D:\Користувачі"

# Якщо диска D: немає - шлях профілів не змінюємо, інакше нові користувачі не зможуть увійти
if (-not (Test-Path "D:\")) {
    Write-Host "Диск D: не знайдено. Шлях папок користувачів не змінено." -ForegroundColor Red
    return
}

# Створюємо папку, якщо її ще немає
if (-not (Test-Path $newProfilePath)) {
    New-Item -ItemType Directory -Path $newProfilePath | Out-Null
    Write-Host "Створено папку $newProfilePath" -ForegroundColor Green
}

# Змінюємо ключ реєстру ProfileList на новий шлях
$regPath = "HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\ProfileList"
Set-ItemProperty -Path $regPath -Name "ProfilesDirectory" -Value $newProfilePath

Write-Host "Відтепер папки нових користувачів створюватимуться в $newProfilePath" -ForegroundColor Yellow

}

function ImportAppLockerRules {

   Write-Host ""
   Write-Host "Чи бажаєте ви застосувати правила 'AppLocker'?" -ForegroundColor Cyan
   Write-Host "Застосувати нові з видаленням старих правил (1), Додати нові правила до вже існуючих (2), Не застосовувати (3)" -ForegroundColor Yellow
   $appLockerChoice = Read-Host "Введіть ваш вибір: " 

    $xmlPath = ".\AppLocker_Policy.xml"

    if (-not (Test-Path $xmlPath)) {
        Write-Error "Файл $xmlPath не знайдено. Операцію скасовано."
        return
    }

    switch ($appLockerChoice) {
        "1" {
            try {
                Write-Host "Імпорт правил з видаленням старих..." -ForegroundColor Yellow
                Set-AppLockerPolicy -XMLPolicy $xmlPath
                Write-Host "Правила AppLocker застосовано." -ForegroundColor Green
            }
            catch {
                Write-Host "Помилка при імпорті правил AppLocker." -ForegroundColor Red
            }
            return
        }
        "2" {
            try {
                Write-Host "Додавання правил до існуючих..." -ForegroundColor Yellow
                Set-AppLockerPolicy -XMLPolicy $xmlPath -Merge
                Write-Host "Правила AppLocker застосовано." -ForegroundColor Green
            }
            catch {
                Write-Host "Помилка при імпорті правил AppLocker (Merge)." -ForegroundColor Red
            }
            return
        }
        "3" {
            Write-Host "Правила AppLocker не було застосовано." -ForegroundColor Gray
            return
        }
        default {
            Write-Host "Невірний вибір, спробуйте ще раз." -ForegroundColor Red
            return
        }
    }

     Write-Host ""

}

function createNewUser {
cls

Write-Host "┌──────────────────────────────────────────────────────────────────────────────────────────────────────────────────────┐" -ForegroundColor Yellow
Write-Host "│## В даному скрипті під час налаштування ПОЛІТИК БЕЗПЕКИ буде змінено стандартний шлях папок для нових користувачів ##│" -ForegroundColor Yellow
Write-Host "│##                  'C:\Користувачі\<Ім'я користувача>' на 'D:\Користувачі\<Ім'я користувача>'                      ##│" -ForegroundColor Yellow
Write-Host "│----------------------------------------------------------------------------------------------------------------------│" -ForegroundColor Yellow
Write-Host "│##               ЗВЕРТАЮ УВАГУ, що при створені користувача робочі папки не створюються.                            ##│" -ForegroundColor Yellow
Write-Host "│##           Створення даних папок відбувається лише при першому вході користувача в систему.                       ##│" -ForegroundColor Yellow
Write-Host "└──────────────────────────────────────────────────────────────────────────────────────────────────────────────────────┘" -ForegroundColor Yellow

while ($true) {# Цикл, що буде продовжуватись, поки ім'я не буде унікальним

$Script:newUserName = Read-Host "Введіть ім'я нового користувача"

$userExist = Get-LocalUser -Name $Script:newUserName -ErrorAction SilentlyContinue

if ($userExist) {
    Write-Host "Обліковий запис з іменем '$Script:newUserName' вже присутній в системі" -ForegroundColor Green

} else {
    Write-Host "Обліковий запис $Script:newUserName створено" -ForegroundColor Green
    break #Вихід з циклу, якщо користувач не існує
    }
}

$newUserFullName = Read-Host "Введіть повне ім'я користувача"

$newUserDescription = Read-Host "Введіть опис користувача"

#Перевірка паролів
$passwordMatch = $false

while ($passwordMatch -ne $true) {

        $newUserPassword =  Read-Host "Введіть пароль користувача"

        $newUserPasswordConfirm = Read-Host "Підтвердіть пароль користувача"

        if ( $newUserPassword -eq "") {
        Write-Host "---------------------------------------------------------------------------" -ForegroundColor DarkYellow
        Write-Host "Значення паролю не може бути 'пустим'" -ForegroundColor Red
        Write-Host "---------------------------------------------------------------------------" -ForegroundColor DarkYellow
        $passwordMatch = $false
        } else {
        if ($newUserPassword -eq $newUserPasswordConfirm) {

            Write-Host "Паролі співпадають" -ForegroundColor Green

            $passwordMatch = $true

            } else {

            Write-Host "Паролі не співпадають. Повторіть спробу ще раз." -ForegroundColor Red

            $passwordMatch = $false       
                    }            
            }   
        }
    
    # Перетворення пароля у формат SecureString
    $newUserSecurePassword = ConvertTo-SecureString $newUserPassword -AsPlainText -Force

    # Створення користувача
    New-LocalUser -Name $Script:newUserName -Password $newUserSecurePassword -FullName $newUserFullName -Description $newUserDescription | Out-Null

     # Додавання користувача до групи "Users"
    Add-LocalGroupMember -Group "Users" -Member $Script:newUserName

    Write-Host "Користувач '$Script:newUserName' успішно створений і доданий до групи 'Users'!" -ForegroundColor Green

    # Змусити користувача змінити пароль при наступному вході
    try {
    net user $Script:newUserName /logonpasswordchg:yes | Out-Null
    Write-Host "Користувач $Script:newUserName має змінити пароль при наступному вході в систему" -ForegroundColor Green
    }
     catch {
    Write-Host "Помилка під час встановлення параметру 'Користувач має змінити пароль при наступному вході' " -ForegroundColor Red
    Write-Host $_.Exception.Message -ForegroundColor Yellow
    }

    $addAnotherUser = (Read-Host "Бажаєте додати ще одного користувача ? Так(Y), Повернутись до головного меню (N), Вийти (X)").ToUpper()
    switch ($addAnotherUser) {
        "Y" { createNewUser }
        "N" { Start-Menu }
        "X" { End }
        default { Write-Host "Invalid choice, try again."; End}
        }



}

